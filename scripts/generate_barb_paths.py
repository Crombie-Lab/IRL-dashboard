#!/usr/bin/env python3
"""Regenerate checked-in Matplotlib SVG geometry (development only).

Requires matplotlib==3.10.8. The hourly build and unit tests do not import it.
Run: MPLCONFIGDIR=/tmp/irl-mpl-config python3 scripts/generate_barb_paths.py
"""
import json
import math
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

if matplotlib.__version__ != '3.10.8':
    raise SystemExit('Use matplotlib==3.10.8 to reproduce the checked-in paths')

root = Path(__file__).resolve().parents[1]
# Forecast parser accepts up to 360 m/s (~700 knots). Keep every 5-knot symbol.
speeds = list(range(0, 701, 5))
fig, ax = plt.subplots()
barbs = ax.barbs([0] * len(speeds), [0] * len(speeds), [0] * len(speeds),
                [-speed for speed in speeds], length=28, pivot='middle', rounding=False)
paths = []
scales = []
for path in barbs.get_paths():
    commands = []
    for (x, y), code in zip(path.vertices, path.codes):
        if code == 79:
            commands.append('Z')
        else:
            # Matplotlib is y-up; SVG is y-down. The canonical shaft points north.
            x, y = (round(float(v), 3) + 0 for v in (x, -y))
            commands.append(('M' if code == 1 else 'L') + f'{x:g},{y:g}')
    paths.append(' '.join(commands))
    # Very high speeds have many flags. Fit those without clipping after rotation.
    radius = max(math.hypot(x, y) for x, y in path.vertices)
    scales.append(round(min(1, 25 / radius), 6))
plt.close(fig)
body = {'version': matplotlib.__version__, 'step_knots': 5, 'max_knots': 700,
        'paths': paths, 'scales': scales}
asset = root / 'assets/vendor/matplotlib-barbs.js'
asset.write_text('// Generated by scripts/generate_barb_paths.py using Matplotlib 3.10.8.\n'
                 '// Matplotlib license: matplotlib.LICENSE. No runtime dependency.\n'
                 'window.MatplotlibBarbPaths=Object.freeze(' + json.dumps(body, separators=(',', ':')) + ');\n')
license_path = Path(matplotlib.__file__).parent.parent / 'matplotlib-3.10.8.dist-info/LICENSE'
(root / 'assets/vendor/matplotlib.LICENSE').write_text(license_path.read_text())
print(f'Generated {len(paths)} Matplotlib symbols ({asset.stat().st_size} bytes)')
